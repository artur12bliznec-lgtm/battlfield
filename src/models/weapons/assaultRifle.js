import { Parts, profile, rounded, box, cylinder, lathe, rod, sphere, DEG } from '../kit.js';
import { assembleWeapon } from './common.js';

/**
 * Автомат в духе АКМ / АК-74: деревянные приклад и цевьё, изогнутый
 * «рыжий» магазин, газовая трубка над стволом, дульный тормоз.
 *
 * Чертёжные координаты: ось канала ствола — y = 0, задний торец ствольной
 * коробки — z = 0, ствол смотрит в +Z. Длина ~0,94 м.
 */
export function createAssaultRifle() {
  const p = new Parts();

  // --- Ствольная коробка ---
  p.add(profile(rounded([[-0.004, 0.004], [0.215, 0.004], [0.215, -0.04], [0.19, -0.047], [0.0, -0.047], [-0.004, -0.04]], 0.002), 0.034, { bevel: 0.002 }), 'gunmetal');
  // крышка ствольной коробки
  p.add(box(0.031, 0.026, 0.2, 0.011).translate(0, 0.014, 0.107), 'gunmetal');
  // кнопка фиксатора крышки
  p.add(box(0.012, 0.01, 0.014, 0.003).translate(0, 0.016, 0.002), 'steel');
  // окно выброса гильз и затворная рама (правая сторона, −X)
  p.add(box(0.002, 0.015, 0.075).translate(-0.0168, 0.004, 0.135), 'darkSteel');
  // рукоятка затворной рамы
  p.add(rod([-0.016, 0.01, 0.172], [-0.036, 0.012, 0.172], 0.0042), 'steel');
  p.add(sphere(0.0068, 8, 6).scale(1, 0.9, 1.2).translate(-0.039, 0.012, 0.172), 'steel');
  // переводчик огня — длинный рычаг справа
  p.add(box(0.003, 0.012, 0.115, 0.001).rotateX(-3 * DEG).translate(-0.0185, -0.002, 0.108), 'steel');
  p.add(box(0.004, 0.02, 0.01, 0.001).translate(-0.019, -0.006, 0.168), 'steel');

  // --- Колодка и прицельная планка ---
  p.add(profile(rounded([[0.195, 0.026], [0.235, 0.026], [0.255, 0.012], [0.255, -0.02], [0.195, -0.02]], 0.003), 0.032, { bevel: 0.002 }), 'gunmetal');
  p.add(box(0.022, 0.004, 0.05, 0.001).rotateX(2 * DEG).translate(0, 0.0285, 0.225), 'steel');
  p.add(box(0.02, 0.009, 0.007, 0.001).translate(0, 0.0345, 0.205), 'steel'); // хомутик с целиком

  // --- Приклад ---
  p.add(profile(rounded([
    [0.0, 0.006, 0],
    [-0.25, -0.029, 0.014],
    [-0.262, -0.18, 0.012],
    [-0.215, -0.18, 0.02],
    [-0.06, -0.076, 0.035],
    [0.0, -0.047, 0],
  ]), 0.042, { bevel: 0.006, bevelSegments: 2 }), 'wood');
  p.add(box(0.045, 0.142, 0.008, 0.002).translate(0, -0.106, -0.265), 'gunmetal'); // затыльник

  // --- Пистолетная рукоятка ---
  p.add(profile(rounded([[0.066, -0.044, 0], [0.022, -0.044, 0], [-0.011, -0.158, 0.012], [0.034, -0.156, 0.012]]), 0.03, { bevel: 0.004, bevelSegments: 2 }), 'bakelite');

  // --- Спусковая скоба и крючок ---
  p.add(profile(rounded([
    [0.066, -0.044, 0], [0.066, -0.084, 0.014], [0.148, -0.084, 0.016], [0.15, -0.044, 0],
    [0.143, -0.044, 0], [0.141, -0.077, 0.01], [0.073, -0.077, 0.008], [0.073, -0.044, 0],
  ]), 0.012, { bevel: 0.001 }), 'gunmetal');
  p.add(profile([[0.092, -0.046], [0.098, -0.046], ['q', 0.099, -0.06, 0.106, -0.07], [0.102, -0.072], ['q', 0.092, -0.063, 0.092, -0.046]], 0.006, { bevel: 0.001 }), 'steel');

  // --- Цевьё и накладка газовой трубки (дерево) ---
  p.add(profile(rounded([[0.257, 0.004, 0], [0.43, 0.004, 0], [0.43, -0.035, 0.012], [0.29, -0.041, 0.02], [0.257, -0.034, 0.01]]), 0.046, { bevel: 0.008, bevelSegments: 2 }), 'wood');
  p.add(box(0.03, 0.022, 0.162, 0.01).translate(0, 0.02, 0.338), 'wood');
  p.add(box(0.048, 0.044, 0.012, 0.005).translate(0, -0.0155, 0.436), 'gunmetal'); // передняя обойма цевья

  // --- Газовая трубка, газовый блок, ствол ---
  p.add(cylinder(0.0085, 0.0085, 0.05, 12, 'z').translate(0, 0.021, 0.444), 'gunmetal');
  p.add(box(0.026, 0.046, 0.034, 0.006).translate(0, 0.008, 0.481), 'gunmetal');
  p.add(cylinder(0.0095, 0.0095, 0.4, 12, 'z').translate(0, 0, 0.4), 'gunmetal');
  p.add(cylinder(0.0028, 0.0028, 0.152, 6, 'z').translate(0, -0.017, 0.516), 'steel'); // шомпол

  // --- Основание мушки, мушка с «ушками» ---
  p.add(profile(rounded([[0.552, -0.022], [0.592, -0.022], [0.592, 0.03], [0.566, 0.03], [0.552, 0.008]], 0.004), 0.024, { bevel: 0.002 }), 'gunmetal');
  for (const side of [-1, 1]) p.add(box(0.003, 0.022, 0.014, 0.001).translate(side * 0.0105, 0.04, 0.575), 'gunmetal');
  p.add(cylinder(0.0016, 0.0016, 0.016, 6).translate(0, 0.038, 0.575), 'steel');

  // --- Дульный тормоз ---
  p.add(lathe([[0, 0.598], [0.0105, 0.598], [0.0125, 0.603], [0.0125, 0.672], [0.0105, 0.68], [0, 0.68]], 14, 'z'), 'gunmetal', { crease: 50 });
  p.add(box(0.0262, 0.007, 0.016).translate(0, 0, 0.655), 'darkSteel'); // боковые окна
  p.add(cylinder(0.0055, 0.0055, 0.003, 10, 'z').translate(0, 0, 0.6795), 'darkSteel'); // канал ствола

  // --- Магазин (отдельный узел — для анимации перезарядки) ---
  const mag = new Parts();
  mag.add(profile([
    [0.152, -0.036], [0.214, -0.036],
    ['q', 0.232, -0.15, 0.29, -0.236],
    [0.243, -0.262],
    ['q', 0.168, -0.17, 0.152, -0.036],
  ], 0.03, { bevel: 0.004, bevelSegments: 2, curveSegments: 8 }), 'bakelite');
  mag.add(profile([[0.291, -0.233], [0.2935, -0.2405], [0.2445, -0.2665], [0.242, -0.259]], 0.034, { bevel: 0.0015 }), 'bakelite');

  return assembleWeapon({
    id: 'assault_rifle',
    body: p,
    movable: { magazine: { parts: mag, pivot: [0, -0.036, 0.152] } },
    grip: [0, -0.095, 0.028],
    gripAngle: 17 * DEG,
    points: {
      grip_l: [0, -0.017, 0.35],
      sight: [0, 0.037, -0.06],
      muzzle: [0, 0, 0.682],
      stock: [0, -0.106, -0.27],
      eject: [-0.018, 0.004, 0.135],
    },
    info: { caliber: '5,45×39 мм', capacity: 30, rpm: 650, modes: 'авто / одиночный' },
  });
}
