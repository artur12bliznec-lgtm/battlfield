import { Parts, profile, rounded, box, cylinder, lathe, rod, DEG } from '../kit.js';
import { assembleWeapon } from './common.js';

/**
 * Единый пулемёт в духе ПКМ: скелетный приклад, крышка ствольной коробки,
 * короб на 100 патронов с лентой, газовый цилиндр под стволом, складные
 * сошки, рукоятка для переноски, щелевой пламегаситель.
 *
 * Чертёжные координаты: ось канала ствола — y = 0, задний торец
 * ствольной коробки — z = 0. Длина ~1,25 м.
 */
export function createMachineGun() {
  const p = new Parts();

  // --- Ствольная коробка и крышка ---
  p.add(profile(rounded([[0.0, 0.016], [0.3, 0.016], [0.3, -0.03], [0.33, -0.03], [0.33, -0.05], [0.0, -0.056]], 0.004), 0.046, { bevel: 0.002 }), 'gunmetal');
  p.add(box(0.05, 0.022, 0.205, 0.007).translate(0, 0.025, 0.115), 'gunmetal');
  p.add(box(0.02, 0.005, 0.16).translate(0, 0.037, 0.12), 'gunmetal'); // ребро крышки
  p.add(box(0.034, 0.012, 0.012, 0.003).translate(0, 0.02, 0.006), 'steel'); // защёлка крышки
  // приёмник ленты справа и окно выброса гильз слева
  p.add(box(0.012, 0.03, 0.09, 0.003).translate(-0.027, -0.004, 0.21), 'gunmetal');
  p.add(box(0.002, 0.014, 0.05).translate(0.0236, -0.02, 0.19), 'darkSteel');
  // рукоятка перезаряжания справа
  p.add(rod([-0.022, -0.035, 0.27], [-0.05, -0.035, 0.27], 0.0045), 'steel');
  p.add(box(0.012, 0.02, 0.016, 0.004).translate(-0.054, -0.035, 0.27), 'steel');

  // --- Прицел ---
  p.add(box(0.034, 0.03, 0.05, 0.004).translate(0, 0.03, 0.245), 'gunmetal');
  p.add(box(0.02, 0.005, 0.046, 0.001).rotateX(2 * DEG).translate(0, 0.047, 0.247), 'steel');
  p.add(box(0.018, 0.008, 0.008, 0.001).translate(0, 0.053, 0.23), 'steel');

  // --- Скелетный приклад ---
  p.add(profile(rounded([
    [0.0, 0.013, 0], [-0.385, -0.016, 0.012], [-0.392, -0.168, 0.01], [-0.32, -0.172, 0.02],
    [-0.08, -0.088, 0.03], [-0.01, -0.056, 0.01], [0.0, -0.05, 0],
  ]), 0.04, {
    bevel: 0.005,
    bevelSegments: 2,
    holes: [rounded([[-0.07, -0.017], [-0.345, -0.037], [-0.352, -0.128], [-0.305, -0.137], [-0.11, -0.069]], 0.014)],
  }), 'polymer');
  p.add(box(0.044, 0.156, 0.012, 0.004).rotateX(-1.5 * DEG).translate(0, -0.093, -0.396), 'rubber');

  // --- Рукоятка, скоба, крючок ---
  p.add(profile(rounded([[0.062, -0.052, 0], [0.016, -0.052, 0], [-0.012, -0.168, 0.012], [0.032, -0.172, 0.012]]), 0.032, { bevel: 0.005, bevelSegments: 2 }), 'polymer');
  p.add(profile(rounded([
    [0.062, -0.052, 0], [0.062, -0.094, 0.014], [0.143, -0.094, 0.014], [0.145, -0.052, 0],
    [0.137, -0.052, 0], [0.136, -0.087, 0.008], [0.07, -0.087, 0.008], [0.07, -0.052, 0],
  ]), 0.012, { bevel: 0.001 }), 'gunmetal');
  p.add(profile([[0.083, -0.054], [0.089, -0.054], ['q', 0.09, -0.068, 0.097, -0.077], [0.093, -0.079], ['q', 0.083, -0.07, 0.083, -0.054]], 0.007, { bevel: 0.001 }), 'steel');

  // --- Ствол, газовый цилиндр, газовый блок ---
  p.add(lathe([[0, 0.29], [0.0135, 0.29], [0.0135, 0.38], [0.012, 0.42], [0.012, 0.8], [0, 0.8]], 14, 'z'), 'gunmetal', { crease: 50 });
  p.add(cylinder(0.0115, 0.0115, 0.3, 12, 'z').translate(0, -0.03, 0.47), 'gunmetal');
  p.add(box(0.03, 0.06, 0.04, 0.006).translate(0, -0.012, 0.62), 'gunmetal');
  // рукоятка для переноски (сложена влево)
  p.add(box(0.034, 0.036, 0.04, 0.006).translate(0, 0.002, 0.35), 'gunmetal');
  p.add(rod([0.012, 0.004, 0.35], [0.048, 0.016, 0.345], 0.006), 'gunmetal');
  p.add(box(0.022, 0.026, 0.13, 0.009).translate(0.058, 0.018, 0.33), 'polymer');

  // --- Мушка и пламегаситель ---
  p.add(box(0.03, 0.03, 0.035, 0.005).translate(0, 0, 0.778), 'gunmetal');
  p.add(box(0.01, 0.04, 0.022, 0.003).translate(0, 0.03, 0.778), 'gunmetal');
  for (const side of [-1, 1]) p.add(box(0.004, 0.03, 0.016, 0.001).translate(side * 0.011, 0.052, 0.778), 'gunmetal');
  p.add(cylinder(0.0016, 0.0016, 0.03, 6).translate(0, 0.047, 0.778), 'steel');
  p.add(lathe([[0, 0.795], [0.011, 0.795], [0.0135, 0.8], [0.0145, 0.87], [0, 0.87]], 14, 'z'), 'gunmetal', { crease: 50 });
  p.add(box(0.0302, 0.004, 0.045).translate(0, 0, 0.848), 'darkSteel'); // прорези
  p.add(box(0.004, 0.0302, 0.045).translate(0, 0, 0.848), 'darkSteel');
  p.add(cylinder(0.0065, 0.0065, 0.002, 10, 'z').translate(0, 0, 0.8705), 'darkSteel');

  // --- Короб с лентой (отдельный узел, как магазин) ---
  const box100 = new Parts();
  box100.add(box(0.075, 0.14, 0.115, 0.006).translate(-0.012, -0.14, 0.212), 'olivePaint');
  box100.add(box(0.078, 0.008, 0.118, 0.002).translate(-0.012, -0.068, 0.212), 'olivePaint'); // крышка
  for (const y of [-0.11, -0.165]) box100.add(box(0.078, 0.006, 0.1, 0.002).translate(-0.012, y, 0.212), 'olivePaint'); // рёбра
  box100.add(box(0.03, 0.016, 0.04, 0.004).translate(-0.006, -0.062, 0.212), 'gunmetal'); // кронштейн
  box100.add(rod([-0.03, -0.12, 0.2715], [0.006, -0.12, 0.2715], 0.003), 'gunmetal'); // ручка короба
  // лента: патроны идут из короба в приёмник справа
  const belt = [[-0.034, -0.07], [-0.052, -0.062], [-0.064, -0.047], [-0.066, -0.03], [-0.059, -0.015], [-0.046, -0.005]];
  for (const [x, y] of belt) {
    box100.add(cylinder(0.006, 0.0056, 0.05, 8, 'z').translate(x, y, 0.197), 'brass');
    box100.add(cylinder(0.0039, 0.0, 0.024, 8, 'z').translate(x, y, 0.234), 'copper');
    box100.add(cylinder(0.0068, 0.0068, 0.009, 8, 'z').translate(x, y, 0.2), 'darkSteel'); // звено ленты
  }

  // --- Сошки (сложены назад вдоль газового цилиндра) ---
  const legs = {};
  for (const [name, side] of [['bipod_leg_l', 1], ['bipod_leg_r', -1]]) {
    const leg = new Parts();
    const x = side * 0.018;
    leg.add(rod([x, -0.04, 0.615], [x, -0.04, 0.33], 0.0055), 'gunmetal');
    leg.add(box(0.008, 0.012, 0.03, 0.002).translate(x, -0.044, 0.325), 'gunmetal');
    legs[name] = { parts: leg, pivot: [x, -0.04, 0.615] };
  }
  p.add(box(0.044, 0.014, 0.02, 0.003).translate(0, -0.04, 0.615), 'gunmetal');

  return assembleWeapon({
    id: 'machine_gun',
    hold: 'long',
    bipodFoldsForward: false,
    body: p,
    movable: { magazine: { parts: box100, pivot: [-0.012, -0.068, 0.212] }, ...legs },
    grip: [0, -0.11, 0.025],
    points: {
      sight: [0, 0.055, -0.05],
      muzzle: [0, 0, 0.871],
      stock: [0, -0.093, -0.402],
      eject: [0.025, -0.02, 0.19],
    },
    info: { caliber: '7,62×54 мм R', capacity: 100, rpm: 700, modes: 'авто', bipod: ['bipod_leg_l', 'bipod_leg_r'] },
  });
}
