import { Parts, profile, rounded, box, cylinder } from '../kit.js';
import { assembleWeapon } from './common.js';

/**
 * Пистолет в духе Glock 17: полимерная рамка, затвор-кожух с насечками,
 * три точки на прицельных приспособлениях.
 *
 * Чертёжные координаты: ось канала ствола — y = 0, задний торец
 * затвора — z = 0. Длина ~0,19 м.
 */
export function createPistol() {
  const p = new Parts();

  // --- Затвор-кожух с прицельными приспособлениями — отдельный узел slide ---
  const slide = new Parts();
  slide.add(profile(rounded([[0.0, -0.015, 0.002], [0.186, -0.015, 0.002], [0.186, 0.006, 0.004], [0.178, 0.0145, 0.003], [0.003, 0.0145, 0.003], [0.0, 0.01, 0.002]]), 0.0255, { bevel: 0.003 }), 'gunmetal');
  for (const side of [-1, 1]) {
    for (let i = 0; i < 7; i++) slide.add(box(0.0012, 0.02, 0.0022).translate(side * 0.0128, -0.002, 0.008 + i * 0.0045), 'darkSteel');
  }
  slide.add(box(0.0022, 0.009, 0.05).translate(-0.0118, 0.0085, 0.098), 'steel'); // окно выброса: виден казённик ствола
  slide.add(box(0.0035, 0.0055, 0.006, 0.0008).translate(0, 0.017, 0.177), 'polymer');
  slide.add(box(0.0016, 0.0016, 0.0008).translate(0, 0.0182, 0.1737), 'sightDot');
  slide.add(box(0.015, 0.002, 0.007).translate(0, 0.0152, 0.012), 'polymer');
  for (const side of [-1, 1]) {
    slide.add(box(0.0055, 0.006, 0.007, 0.0008).translate(side * 0.0045, 0.0172, 0.012), 'polymer');
    slide.add(box(0.0016, 0.0016, 0.0008).translate(side * 0.0045, 0.0185, 0.0083), 'sightDot');
  }
  // ствол остаётся на месте, когда кожух откатывается
  p.add(box(0.017, 0.003, 0.05).translate(0, 0.0135, 0.098), 'steel'); // казённик ствола в окне
  p.add(cylinder(0.0066, 0.0066, 0.002, 12, 'z').translate(0, 0, 0.1865), 'steel');
  p.add(cylinder(0.0045, 0.0045, 0.002, 10, 'z').translate(0, 0, 0.1875), 'darkSteel');

  // --- Рамка с рукоятью и спусковой скобой ---
  p.add(profile(rounded([
    [0.176, -0.013, 0], [0.176, -0.028, 0.002], [0.104, -0.028, 0.002],
    [0.101, -0.033, 0.002], [0.097, -0.058, 0.004], [0.093, -0.062, 0.003], [0.052, -0.061, 0.006],
    [0.045, -0.055, 0.006],
    [0.016, -0.128, 0.004], [0.012, -0.135, 0.003], [-0.026, -0.134, 0.003], [-0.031, -0.128, 0.004],
    [0.003, -0.042, 0.006], [-0.008, -0.025, 0.006], [-0.002, -0.014, 0.003], [0.004, -0.013, 0],
  ]), 0.029, {
    bevel: 0.004,
    bevelSegments: 2,
    holes: [rounded([[0.092, -0.031], [0.088, -0.054], [0.055, -0.054], [0.052, -0.044], [0.056, -0.031]], 0.004)],
  }), 'polymer');
  // крючок, затворная задержка, рычаг разборки, слоты планки
  p.add(profile(rounded([[0.067, -0.031], [0.073, -0.031], [0.076, -0.05], [0.071, -0.052]], 0.001), 0.006, { bevel: 0.0008 }), 'polymer');
  p.add(box(0.0022, 0.004, 0.018, 0.001).translate(0.0148, -0.016, 0.07), 'polymer');
  for (const side of [-1, 1]) p.add(box(0.0022, 0.005, 0.007, 0.001).translate(side * 0.0148, -0.021, 0.098), 'steel');
  for (const z of [0.132, 0.15]) p.add(box(0.0305, 0.003, 0.004).translate(0, -0.026, z), 'darkSteel');

  // --- Магазин: внутри рукояти видно только донце ---
  const mag = new Parts();
  mag.add(profile(rounded([[0.03, -0.035], [0.006, -0.135], [-0.022, -0.135], [0.002, -0.035]], 0.002), 0.022, { bevel: 0.001 }), 'gunmetal');
  mag.add(box(0.031, 0.006, 0.043, 0.002).translate(0, -0.1375, -0.0075), 'polymer');

  return assembleWeapon({
    id: 'pistol',
    hold: 'pistol',
    body: p,
    movable: {
      magazine: { parts: mag, pivot: [0, -0.035, 0.002] },
      slide: { parts: slide, pivot: [0, 0, 0] },
    },
    grip: [0, -0.085, 0.0095],
    points: {
      sight: [0, 0.019, -0.42],
      muzzle: [0, 0, 0.188],
      eject: [-0.013, 0.01, 0.098],
    },
    info: { caliber: '9×19 мм', capacity: 17, rpm: 400, modes: 'одиночный' },
  });
}
