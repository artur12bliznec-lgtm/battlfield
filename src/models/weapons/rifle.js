import { Parts, profile, rounded, box, cylinder, lathe, rod } from '../kit.js';
import { assembleWeapon } from './common.js';

/**
 * Штурмовая винтовка в духе M4: чёрный анодированный корпус, фурнитура
 * цвета «койот», планка сверху, складной целик и мушка-«треугольник»,
 * ребристое цевьё, телескопический приклад, магазин на 30 патронов.
 *
 * Чертёжные координаты: ось канала ствола — y = 0, задний торец верхней
 * части ствольной коробки — z = 0. Длина ~0,78 м.
 */
export function createRifle() {
  const p = new Parts();

  // --- Верхняя часть ствольной коробки и планка ---
  p.add(profile(rounded([[0.0, -0.013], [0.178, -0.013], [0.178, 0.022], [0.006, 0.022], [0.0, 0.015]], 0.003), 0.03, { bevel: 0.002 }), 'anodized');
  p.add(box(0.021, 0.006, 0.174).translate(0, 0.025, 0.089), 'anodized');
  for (let i = 0; i < 17; i++) p.add(box(0.021, 0.004, 0.0052).translate(0, 0.03, 0.006 + i * 0.01), 'anodized');
  // рукоятка заряжания сзади
  p.add(box(0.012, 0.008, 0.03, 0.002).translate(0, 0.017, -0.006), 'anodized');
  p.add(box(0.042, 0.008, 0.01, 0.002).translate(0, 0.017, -0.018), 'anodized');
  // справа: окно выброса, отражатель гильз, досылатель
  p.add(box(0.0022, 0.016, 0.06).translate(-0.0151, 0.004, 0.1), 'darkSteel');
  p.add(box(0.008, 0.016, 0.014, 0.003).translate(-0.016, 0.008, 0.062), 'anodized');
  p.add(rod([-0.012, 0.009, 0.05], [-0.024, 0.012, 0.028], 0.0072, 0.0072, 10), 'anodized');
  p.add(rod([-0.024, 0.012, 0.028], [-0.0265, 0.0125, 0.0232], 0.0088, 0.0088, 10), 'anodized');

  // --- Нижняя часть: шахта магазина, органы управления ---
  p.add(profile(rounded([
    [-0.004, -0.012, 0], [0.172, -0.012, 0], [0.172, -0.03, 0.002], [0.168, -0.071, 0.002],
    [0.172, -0.079, 0.002], [0.104, -0.079, 0.002], [0.107, -0.071, 0.002], [0.107, -0.046, 0.003],
    [0.045, -0.046, 0.004], [0.012, -0.05, 0.006], [-0.004, -0.04, 0.004],
  ]), 0.03, { bevel: 0.002 }), 'anodized');
  p.add(cylinder(0.0045, 0.0045, 0.004, 12, 'x').translate(-0.0165, -0.036, 0.1), 'anodized'); // защёлка магазина
  p.add(box(0.004, 0.018, 0.012, 0.001).translate(0.0165, -0.03, 0.096), 'anodized'); // затворная задержка
  p.add(box(0.003, 0.008, 0.022, 0.001).translate(0.0165, -0.03, 0.032), 'anodized'); // переводчик
  for (const [y, z] of [[-0.03, 0.16], [-0.022, 0.004]]) p.add(cylinder(0.003, 0.003, 0.033, 8, 'x').translate(0, y, z), 'steel'); // штифты

  // --- Спусковая скоба, крючок, рукоятка ---
  p.add(profile(rounded([
    [0.045, -0.046, 0], [0.045, -0.07, 0.012], [0.104, -0.072, 0.012], [0.104, -0.046, 0],
    [0.098, -0.046, 0], [0.097, -0.066, 0.008], [0.051, -0.065, 0.008], [0.051, -0.046, 0],
  ]), 0.011, { bevel: 0.001 }), 'anodized');
  p.add(profile([[0.066, -0.048], [0.071, -0.048], ['q', 0.072, -0.058, 0.077, -0.066], [0.073, -0.067], ['q', 0.066, -0.06, 0.066, -0.048]], 0.006, { bevel: 0.001 }), 'steel');
  p.add(profile(rounded([
    [0.043, -0.046, 0], [0.004, -0.046, 0], [-0.03, -0.152, 0.012], [0.006, -0.157, 0.01],
    [0.012, -0.13, 0.006], [0.022, -0.1, 0.012], [0.026, -0.08, 0.006],
  ]), 0.03, { bevel: 0.004, bevelSegments: 2 }), 'tanPolymer');

  // --- Буферная трубка и телескопический приклад ---
  p.add(cylinder(0.0155, 0.0155, 0.205, 16, 'z').translate(0, 0, -0.1055), 'anodized');
  p.add(cylinder(0.019, 0.019, 0.008, 12, 'z').translate(0, 0, -0.008), 'anodized');
  p.add(profile(rounded([
    [-0.15, 0.022, 0.006], [-0.262, 0.026, 0.008], [-0.268, 0.01, 0], [-0.268, -0.1, 0.012],
    [-0.245, -0.106, 0.012], [-0.2, -0.045, 0.02], [-0.15, -0.024, 0.008],
  ]), 0.04, { bevel: 0.005, bevelSegments: 2 }), 'tanPolymer');
  p.add(box(0.042, 0.13, 0.01, 0.004).translate(0, -0.04, -0.272), 'rubber');
  p.add(box(0.01, 0.008, 0.04, 0.002).translate(0, -0.024, -0.17), 'anodized'); // рычаг фиксатора приклада

  // --- Цевьё, ствол, мушка, пламегаситель ---
  const ribs = [[0, 0.188], [0.0225, 0.188]];
  for (let z = 0.192; z < 0.345; z += 0.016) ribs.push([0.0238, z], [0.0238, z + 0.008], [0.0222, z + 0.0085], [0.0222, z + 0.0155]);
  ribs.push([0.0222, 0.352], [0, 0.352]);
  p.add(lathe(ribs, 16, 'z'), 'tanPolymer', { crease: 50 });
  p.add(cylinder(0.0265, 0.0265, 0.012, 16, 'z').translate(0, 0, 0.183), 'anodized'); // кольцо цевья
  p.add(cylinder(0.0205, 0.0205, 0.008, 14, 'z').translate(0, 0, 0.356), 'anodized'); // колпачок цевья
  p.add(cylinder(0.0085, 0.0085, 0.27, 12, 'z').translate(0, 0, 0.315), 'anodized');
  p.add(profile(rounded([[0.372, -0.016], [0.405, -0.016], [0.405, 0.012], [0.398, 0.05], [0.384, 0.05], [0.377, 0.012], [0.372, 0.012]], 0.003), 0.02, { bevel: 0.0015 }), 'anodized');
  for (const s of [-1, 1]) p.add(box(0.004, 0.02, 0.014, 0.001).translate(s * 0.0065, 0.058, 0.391), 'anodized'); // «ушки» мушки
  p.add(cylinder(0.0015, 0.0015, 0.013, 6).translate(0, 0.0565, 0.391), 'steel');
  p.add(box(0.008, 0.012, 0.02, 0.002).translate(0, -0.024, 0.39), 'anodized'); // штык-упор
  p.add(lathe([[0, 0.448], [0.0105, 0.448], [0.011, 0.452], [0.011, 0.5], [0.0095, 0.505], [0, 0.505]], 12, 'z'), 'anodized', { crease: 50 });
  p.add(box(0.0225, 0.004, 0.03).translate(0, 0.004, 0.478), 'darkSteel'); // прорези пламегасителя
  p.add(box(0.004, 0.0115, 0.03).translate(0, 0.006, 0.478), 'darkSteel');
  p.add(cylinder(0.005, 0.005, 0.002, 10, 'z').translate(0, 0, 0.5055), 'darkSteel');

  // --- Складной целик на планке ---
  p.add(box(0.022, 0.008, 0.028, 0.002).translate(0, 0.037, 0.022), 'anodized');
  p.add(box(0.017, 0.026, 0.006, 0.002).translate(0, 0.053, 0.03), 'anodized');
  p.add(cylinder(0.0035, 0.0035, 0.007, 10, 'z').translate(0, 0.062, 0.03), 'darkSteel');

  // --- Магазин ---
  const mag = new Parts();
  mag.add(profile([
    [0.108, -0.058], [0.168, -0.058], [0.171, -0.15],
    ['q', 0.174, -0.2, 0.192, -0.245],
    [0.14, -0.252],
    ['q', 0.122, -0.2, 0.112, -0.15],
  ], 0.026, { bevel: 0.003, bevelSegments: 2, curveSegments: 8 }), 'tanPolymer');
  mag.add(profile([[0.19, -0.243], [0.196, -0.25], [0.139, -0.259], [0.137, -0.251]], 0.03, { bevel: 0.0015 }), 'tanPolymer');
  for (const [y, z] of [[-0.11, 0.14], [-0.13, 0.142]]) mag.add(box(0.0285, 0.004, 0.05, 0.001).translate(0, y, z), 'tanPolymer');

  return assembleWeapon({
    id: 'rifle',
    hold: 'long',
    body: p,
    movable: { magazine: { parts: mag, pivot: [0, -0.058, 0.108] } },
    grip: [0, -0.1, 0.004],
    points: {
      sight: [0, 0.062, -0.06],
      muzzle: [0, 0, 0.506],
      stock: [0, -0.04, -0.273],
      eject: [-0.016, 0.004, 0.1],
    },
    info: { caliber: '5,56×45 мм', capacity: 30, rpm: 800, modes: 'авто / одиночный' },
  });
}
