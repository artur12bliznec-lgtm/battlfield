import { Parts, profile, rounded, box, cylinder, lathe, rod, sphere, DEG } from '../kit.js';
import { assembleWeapon } from './common.js';

/**
 * Снайперская винтовка с продольно-скользящим затвором в духе AWM:
 * зелёная ложа с отверстием под большой палец и облегчённым прикладом,
 * регулируемая щека, оптический прицел, складные сошки.
 *
 * Чертёжные координаты: ось канала ствола — y = 0, задний торец
 * ствольной коробки — z = 0. Длина ~1,15 м.
 */
export function createSniperRifle() {
  const p = new Parts();

  // --- Ложа ---
  p.add(profile(rounded([
    [0.536, -0.016, 0.012],
    [0.536, -0.068, 0.012],
    [0.024, -0.068, 0.014],
    [0.004, -0.17, 0.012],
    [-0.05, -0.17, 0.014],
    [-0.08, -0.146, 0.02],
    [-0.352, -0.142, 0.014],
    [-0.352, -0.004, 0.012],
    [-0.04, -0.004, 0.02],
    [-0.005, -0.012, 0.006],
    [0.23, -0.012, 0.004],
    [0.245, -0.016, 0],
  ]), 0.05, {
    bevel: 0.006,
    bevelSegments: 2,
    holes: [
      rounded([[-0.03, -0.038], [-0.042, -0.13], [-0.1, -0.13], [-0.1, -0.038]], 0.012),
      rounded([[-0.13, -0.035], [-0.13, -0.116], [-0.318, -0.114], [-0.318, -0.035]], 0.016),
    ],
  }), 'greenPolymer');
  p.add(box(0.054, 0.15, 0.014, 0.004).translate(0, -0.073, -0.359), 'rubber'); // затыльник
  p.add(box(0.044, 0.022, 0.17, 0.008).translate(0, 0.005, -0.22), 'polymer'); // щека
  for (const z of [-0.27, -0.17]) p.add(cylinder(0.004, 0.004, 0.012, 8).translate(0, -0.008, z), 'steel');

  // --- Ствольная коробка, планка, затвор ---
  p.add(cylinder(0.021, 0.021, 0.235, 16, 'z').translate(0, 0.004, 0.1075), 'gunmetal');
  p.add(cylinder(0.016, 0.014, 0.04, 14, 'z').translate(0, 0.004, -0.03), 'gunmetal'); // хвостовик затвора
  p.add(box(0.021, 0.006, 0.25).translate(0, 0.028, 0.105), 'gunmetal');
  for (let i = 0; i < 18; i++) p.add(box(0.021, 0.004, 0.0065).translate(0, 0.033, -0.014 + i * 0.0142), 'gunmetal');
  p.add(box(0.004, 0.012, 0.06).translate(-0.0195, 0.012, 0.12), 'darkSteel'); // окно выброса
  // рукоятка затвора с шаром
  p.add(rod([-0.017, 0.012, 0.03], [-0.058, -0.008, 0.012], 0.0045), 'steel');
  p.add(sphere(0.0105, 12, 8).translate(-0.062, -0.01, 0.01), 'steel');

  // --- Спусковая скоба и крючок ---
  p.add(profile(rounded([
    [0.03, -0.066, 0], [0.03, -0.1, 0.012], [0.11, -0.1, 0.012], [0.112, -0.066, 0],
    [0.104, -0.066, 0], [0.103, -0.093, 0.006], [0.038, -0.093, 0.006], [0.038, -0.066, 0],
  ]), 0.012, { bevel: 0.001 }), 'polymer');
  p.add(profile([[0.064, -0.068], [0.07, -0.068], ['q', 0.071, -0.08, 0.077, -0.088], [0.073, -0.09], ['q', 0.064, -0.082, 0.064, -0.068]], 0.006, { bevel: 0.001 }), 'steel');

  // --- Ствол и дульный тормоз ---
  p.add(lathe([[0, 0.2], [0.0128, 0.2], [0.0128, 0.32], [0.0105, 0.62], [0.0105, 0.7], [0, 0.7]], 14, 'z'), 'gunmetal', { crease: 50 });
  p.add(lathe([[0, 0.698], [0.0145, 0.698], [0.0145, 0.766], [0.012, 0.772], [0, 0.772]], 14, 'z'), 'gunmetal', { crease: 50 });
  for (const z of [0.715, 0.733, 0.751]) p.add(box(0.0296, 0.008, 0.009).translate(0, 0, z), 'darkSteel');
  p.add(cylinder(0.006, 0.006, 0.002, 10, 'z').translate(0, 0, 0.7725), 'darkSteel');

  // --- Оптический прицел ---
  const H = 0.06; // высота оси прицела над осью ствола
  p.add(lathe([
    [0, -0.16], [0.019, -0.16], [0.021, -0.15], [0.021, -0.112], [0.0155, -0.085],
    [0.0155, 0.15], [0.026, 0.2], [0.028, 0.255], [0.0275, 0.262], [0, 0.262],
  ], 20, 'z').translate(0, H, 0), 'polymer', { crease: 50 });
  p.add(cylinder(0.0245, 0.0245, 0.002, 20, 'z').translate(0, H, 0.2625), 'lens');
  p.add(cylinder(0.0165, 0.0165, 0.002, 16, 'z').translate(0, H, -0.1605), 'lens');
  p.add(box(0.034, 0.03, 0.05, 0.008).translate(0, H, 0.04), 'polymer'); // седло барабанчиков
  p.add(cylinder(0.013, 0.013, 0.022, 14).translate(0, H + 0.026, 0.04), 'polymer'); // вертикальные поправки
  p.add(cylinder(0.011, 0.011, 0.02, 14, 'x').translate(-0.026, H, 0.04), 'polymer'); // горизонтальные поправки
  p.add(cylinder(0.011, 0.011, 0.016, 14, 'x').translate(0.024, H, 0.04), 'polymer'); // отстройка параллакса
  // кольца крепления
  for (const z of [-0.02, 0.115]) {
    p.add(cylinder(0.0192, 0.0192, 0.016, 16, 'z').translate(0, H, z), 'gunmetal');
    p.add(box(0.024, 0.016, 0.018, 0.002).translate(0, 0.04, z), 'gunmetal');
    p.add(cylinder(0.004, 0.004, 0.01, 8, 'x').translate(0.015, 0.036, z), 'steel');
  }

  // --- Магазин ---
  const mag = new Parts();
  mag.add(profile(rounded([[0.116, -0.06], [0.192, -0.06], [0.196, -0.118], [0.118, -0.118]], 0.004), 0.034, { bevel: 0.003 }), 'polymer');

  // --- Сошки (сложены вдоль ствола; повернуть по X на ~80°, чтобы разложить) ---
  const legs = {};
  for (const [name, side] of [['bipod_leg_l', 1], ['bipod_leg_r', -1]]) {
    const leg = new Parts();
    const x = side * 0.014;
    leg.add(rod([x, -0.074, 0.5], [x, -0.07, 0.72], 0.0055), 'gunmetal');
    leg.add(rod([x, -0.07, 0.68], [x, -0.07, 0.735], 0.0045), 'steel');
    leg.add(box(0.012, 0.01, 0.016, 0.003).translate(x, -0.07, 0.738), 'rubber');
    legs[name] = { parts: leg, pivot: [x, -0.074, 0.5] };
  }
  p.add(box(0.05, 0.016, 0.03, 0.004).translate(0, -0.074, 0.5), 'gunmetal'); // крепление сошек

  return assembleWeapon({
    id: 'sniper_rifle',
    hold: 'long',
    body: p,
    movable: { magazine: { parts: mag, pivot: [0, -0.06, 0.116] }, ...legs },
    grip: [0, -0.11, -0.012],
    points: {
      sight: [0, H, -0.24],
      muzzle: [0, 0, 0.773],
      stock: [0, -0.073, -0.366],
      eject: [-0.022, 0.012, 0.12],
    },
    info: { caliber: '8,6×70 мм', capacity: 5, rpm: 40, modes: 'одиночный', bipod: ['bipod_leg_l', 'bipod_leg_r'] },
  });
}
